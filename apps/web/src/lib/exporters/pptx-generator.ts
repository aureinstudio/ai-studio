import PptxGenJS from "pptxgenjs";
import type {
  CuratorOutput,
  PlannerOutput,
  InfographicOutput,
  PlanningContent,
  SlideMeta,
  Infographic,
} from "@/components/StudioJobResult";

export type PptxExportInput = {
  topic: string;
  level?: string;
  curator: CuratorOutput;
  planner: PlannerOutput;
  planning?: PlanningContent;
  infographics?: InfographicOutput;
};

// ─── KEG 브랜드 토큰 ─────────────────────────────────
const COLORS = {
  primary: "0B1437", // 짙은 네이비 (KEG 메인)
  primaryLight: "1E293B",
  accent: "F59E0B", // 따뜻한 앰버 (교육·지혜)
  accentLight: "FCD34D",
  bgLight: "FAFAF9",
  bgWhite: "FFFFFF",
  textDark: "18181B",
  textMuted: "71717A",
  textOnDark: "F4F4F5",
  border: "E4E4E7",
  divider: "27272A",
} as const;

const FONT = {
  korean: "맑은 고딕",
  englishMono: "Consolas",
} as const;

/**
 * Studio 콘텐츠 → 디자인된 .pptx 파일.
 * KEG 브랜드 톤 (네이비 + 앰버) · 16:9 widescreen · 맑은 고딕.
 *
 * 슬라이드 구성:
 *   1. 표지 (다크 배경, 큰 타이포)
 *   2. 학습 목표 (앰버 강조)
 *   3. 챕터 개요 (목차)
 *   4..N+3. 본문 슬라이드 (인포그래픽 시각화 포함)
 *   N+4. 정리 (학습 목표 재확인)
 */
export async function generatePptx(input: PptxExportInput): Promise<Buffer> {
  const pptx = new PptxGenJS();

  pptx.title = input.topic;
  pptx.author = "KEG AI Studio";
  pptx.company = "KEG · Aurein Studio";
  pptx.subject = input.curator.chapter_title;
  pptx.layout = "LAYOUT_WIDE";

  defineMasters(pptx, input);

  const infMap = new Map<number, Infographic>(
    (input.infographics?.infographics ?? []).map((i) => [i.slide_number, i]),
  );

  addCoverSlide(pptx, input);
  addObjectivesSlide(pptx, input);
  if (input.planning?.outline?.chapter_outline?.length) {
    addOutlineSlide(pptx, input);
  }
  for (const slide of input.planner.slides) {
    addContentSlide(pptx, slide, infMap.get(slide.slide_number));
  }
  addClosingSlide(pptx, input);

  const buf = (await pptx.write({ outputType: "nodebuffer" })) as Buffer;
  return buf;
}

